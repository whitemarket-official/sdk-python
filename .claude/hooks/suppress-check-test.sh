#!/usr/bin/env bash
# Regression tests for the Stop hook suppress-check.sh.
#
# Every case runs in a TEMPORARY git repository: the real project is not touched,
# and the session marker is written there too.
#
# Run from anywhere (only bash, git, jq, python3):
#   bash .claude/hooks/suppress-check-test.sh
# Exit code: 0 when every case passes, 1 otherwise.

set -u

HOOK="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/suppress-check.sh"
[ -f "$HOOK" ] || { echo "missing $HOOK"; exit 1; }

fail=0
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

PYPROJECT_SEED='[project]
name = "whitemarket-sdk"

[tool.ruff.lint]
select = ["B", "S"]
ignore = [
    "COM812",
]

[tool.ruff.lint.per-file-ignores]
"tests/**" = ["S101"]

[tool.mypy]
strict = true

[tool.pyright]
typeCheckingMode = "strict"

[tool.coverage.run]
omit = []
'

setup_repo() { # clean repo: one committed module, pyproject.toml and a Makefile
  rm -rf "$tmp/repo"
  mkdir -p "$tmp/repo/src/whitemarket"
  git -C "$tmp/repo" init -q
  git -C "$tmp/repo" config user.email test@example.invalid; git -C "$tmp/repo" config user.name test
  git -C "$tmp/repo" config commit.gpgsign false
  printf '"""Module."""\n\n\ndef run() -> None:\n    pass\n' >"$tmp/repo/src/whitemarket/a.py"
  printf '%s' "$PYPROJECT_SEED" >"$tmp/repo/pyproject.toml"
  printf 'audit:\n\t.venv/bin/pip-audit --strict\n' >"$tmp/repo/Makefile"
  git -C "$tmp/repo" add -A >/dev/null
  git -C "$tmp/repo" commit -qm seed
}

# inserts lines $1.. before line 4 (`def run`) of src/whitemarket/a.py
ins() {
  local f="$tmp/repo/src/whitemarket/a.py" body=""
  for l in "$@"; do body="${body}${l}\n"; done
  { head -n 3 "$f"; printf "$body"; tail -n +4 "$f"; } >"$f.new" && mv "$f.new" "$f"
}

# inserts lines $2.. after the first line matching the fixed string $1 in pyproject.toml
ins_toml() {
  local f="$tmp/repo/pyproject.toml" anchor="$1"; shift
  python3 - "$f" "$anchor" "$@" <<'PY'
import sys
path, anchor, *new = sys.argv[1:]
lines = open(path).read().split('\n')
i = next(n for n, l in enumerate(lines) if l == anchor)
lines[i + 1:i + 1] = new
open(path, 'w').write('\n'.join(lines))
PY
}

run() { # $1=session $2=stop_hook_active(true|false)
  printf '{"session_id":"%s","stop_hook_active":%s}' "$1" "$2" \
    | CLAUDE_PROJECT_DIR="$tmp/repo" bash "$HOOK" 2>/dev/null
}

chk() { # $1=want(BLOCK|PASS) $2=label $3=grep pattern inside the reason (optional)
  local out got
  out="$(run "${SESSION:-s1}" false)"
  got=PASS; [ -n "$out" ] && got=BLOCK
  if [ "$got" != "$1" ]; then
    printf '  FAIL  want=%-5s got=%-5s %s\n' "$1" "$got" "$2"; fail=$((fail+1)); return
  fi
  if [ -n "${3:-}" ] && ! printf '%s' "$out" | grep -qF -- "$3"; then
    printf '  FAIL  BLOCK without "%s" %s\n' "$3" "$2"; fail=$((fail+1)); return
  fi
  printf '  ok    %-5s %s\n' "$got" "$2"
}

echo "== Signal A: every Python suppression form without reference + reason =="
n=0
for tag in \
  'x = f()  # type: ignore[attr-defined]' \
  'x = f()  # type: ignore' \
  'x = f()  # noqa: S101' \
  'x = f()  # noqa' \
  '# ruff: noqa: E501' \
  'x = f()  # pyright: ignore[reportUnknownMemberType]' \
  'x = f()  # pyright: ignore' \
  '# pyright: basic' \
  '# pyright: reportUnknownMemberType=false' \
  'x = f()  # nosec B101' \
  '# mypy: ignore-errors' \
  '# mypy: disable-error-code="attr-defined"' \
  'if TYPE_CHECKING:  # pragma: no cover' \
  'if x:  # pragma: no branch' \
  'LIMIT = 300  # pragma: no mutate'; do
  n=$((n + 1))
  setup_repo; ins "$tag"
  SESSION=a$n chk BLOCK "$tag" "src/whitemarket/a.py:4"
done

echo "== Signal A: specific code, reference and reason rules =="
setup_repo; ins 'x = f()  # type: ignore[attr-defined]  # stub lacks the attribute, #12'
SESSION=r1 chk PASS "code + #issue + reason on the same line"

setup_repo; ins 'x = f()  # noqa: S101  # assert is the documented contract here, https://github.com/example/sdk/issues/12'
SESSION=r2 chk PASS "code + issue URL + reason on the same line"

setup_repo; ins '# Generated union lacks a discriminator, see #12' 'x = f()  # pyright: ignore[reportUnknownMemberType]'
SESSION=r3 chk PASS "code on the line, #issue + reason on the previous comment line"

setup_repo; ins 'x = f()  # type: ignore  # stub lacks the attribute, #12'
SESSION=r4 chk BLOCK "bare type: ignore with reference + reason is still blanket" "rule 15"

setup_repo; ins 'x = f()  # noqa  # legacy call kept for parity, #12'
SESSION=r5 chk BLOCK "bare noqa with reference + reason is still blanket"

setup_repo; ins '# Whole module is generated by a third-party tool, #12' '# ruff: noqa'
SESSION=r6 chk BLOCK "file-level ruff: noqa without codes"

setup_repo; ins 'x = f()  # nosec  # input is a constant, not user data, #12'
SESSION=r7 chk BLOCK "nosec without a B-code"

setup_repo; ins 'x = f()  # type: ignore[attr-defined]  # #12'
SESSION=r8 chk BLOCK "#issue without a reason"

setup_repo; ins 'x = f()  # type: ignore[attr-defined]  # stub lacks the attribute'
SESSION=r9 chk BLOCK "reason without an issue reference"

setup_repo; ins 'x = f()  # type: ignore[attr-defined]  # see issue #12'
SESSION=r10 chk BLOCK "filler words (see issue) are not a reason"

setup_repo; ins 'x = f()  # type: ignore[attr-defined]  # false positive, WM-1234'
SESSION=r11 chk BLOCK "Jira-style key is not a GitHub issue reference"

setup_repo; ins 'value = decode_legacy_payload(raw)' 'x = f()  # type: ignore[attr-defined]  #12'
SESSION=r12 chk BLOCK "code on the previous line does not count as a reason"

setup_repo; ins 'x = f()  # noqa: PLR0913, S101  #12'
SESSION=r13 chk BLOCK "rule codes are not reason words"

setup_repo; ins 'if TYPE_CHECKING:  # pragma: no cover  # imports for type checkers only, #7'
SESSION=r14 chk PASS "pragma: no cover with reference + reason"

setup_repo; ins '# an ordinary comment without a suppression' 'x = "type ignore noqa are just words here"'
SESSION=r15 chk PASS "added lines without a suppression"

echo "== Signal A: generated code is not scanned =="
setup_repo; mkdir -p "$tmp/repo/src/whitemarket/_generated" "$tmp/repo/src/whitemarket/_sync"
printf 'x = f()  # type: ignore\n' >"$tmp/repo/src/whitemarket/_generated/client.py"
printf 'x = f()  # type: ignore\n' >"$tmp/repo/src/whitemarket/_sync/client.py"
SESSION=gen chk PASS "_generated and _sync are excluded"

echo "== Signal A: existing suppression and reference in context =="
setup_repo; ins 'x = f()  # type: ignore[attr-defined]'
git -C "$tmp/repo" commit -qam pre >/dev/null
printf '# touch\n' >>"$tmp/repo/src/whitemarket/a.py"
SESSION=c1 chk PASS "suppression existed before the diff"

setup_repo; ins '# Generated union lacks a discriminator, see #12'
git -C "$tmp/repo" commit -qam pre >/dev/null
f="$tmp/repo/src/whitemarket/a.py"; { head -n 4 "$f"; printf 'x = f()  # type: ignore[index]\n'; tail -n +5 "$f"; } >"$f.new" && mv "$f.new" "$f"
SESSION=c2 chk PASS "reason + reference on an unchanged line above the new suppression"

echo "== Signal A: untracked files =="
setup_repo; printf 'x = f()  # type: ignore[index]\n' >"$tmp/repo/src/whitemarket/b.py"
SESSION=u1 chk BLOCK "new module with a suppression" "src/whitemarket/b.py:1"

setup_repo; mkdir -p "$tmp/repo/tests/unit"; printf 'assert x  # noqa: S101\n' >"$tmp/repo/tests/unit/test_b.py"
SESSION=u2 chk BLOCK "new test with a suppression"

setup_repo; printf '# Fixture shape is intentionally invalid, #77\nx = f()  # type: ignore[arg-type]\n' >"$tmp/repo/src/whitemarket/b.py"
SESSION=u3 chk PASS "new module, reference + reason on the line above"

setup_repo; mkdir -p "$tmp/repo/vendor_x"; printf 'x = f()  # type: ignore\n' >"$tmp/repo/vendor_x/c.py"
SESSION=u4 chk PASS "outside src/tests/tools/examples is ignored"

setup_repo; printf 'x = f()  # type: ignore\n' >"$tmp/repo/noxfile.py"
SESSION=u5 chk BLOCK "top-level *.py (noxfile) is scanned"

echo "== Signal A: pyproject.toml =="
setup_repo; ins_toml '"tests/**" = ["S101"]' '"src/whitemarket/live/**" = ["S110"]'
SESSION=t1 chk BLOCK "new ruff per-file-ignores entry" "pyproject.toml:12"

setup_repo; ins_toml '"tests/**" = ["S101"]' '# try-except-pass in the reconnect loop is deliberate, #31' '"src/whitemarket/live/**" = ["S110"]'
SESSION=t2 chk PASS "per-file-ignores entry with reference + reason above"

setup_repo; ins_toml '"tests/**" = ["S101"]' '"src/x/**" = ["S110"]  # reconnect loop swallows by design, #31'
SESSION=t3 chk PASS "per-file-ignores entry with an inline reference + reason"

setup_repo; ins_toml '    "COM812",' '    "PLR0913",'
SESSION=t4 chk BLOCK "rule added to the global ruff ignore list" "PLR0913"

setup_repo; ins_toml 'strict = true' 'ignore_missing_imports = true'
SESSION=t5 chk BLOCK "mypy ignore_missing_imports = true"

setup_repo; ins_toml 'strict = true' '' '[[tool.mypy.overrides]]' 'module = "whitemarket.live.*"' 'disable_error_code = ["attr-defined"]'
SESSION=t6 chk BLOCK "mypy override disable_error_code"

setup_repo; sed -i.bak 's/typeCheckingMode = "strict"/typeCheckingMode = "basic"/' "$tmp/repo/pyproject.toml" && rm -f "$tmp/repo/pyproject.toml.bak"
SESSION=t7 chk BLOCK "pyright typeCheckingMode lowered from strict"

setup_repo; ins_toml 'typeCheckingMode = "strict"' 'reportUnknownMemberType = false'
SESSION=t8 chk BLOCK "pyright report rule switched off"

setup_repo; sed -i.bak 's/^omit = \[\]/omit = ["src\/whitemarket\/live\/*"]/' "$tmp/repo/pyproject.toml" && rm -f "$tmp/repo/pyproject.toml.bak"
SESSION=t9 chk BLOCK "coverage omit gets an entry"

setup_repo; ins_toml '[project]' 'version = "0.1.0"' 'requires-python = ">=3.10"'
SESSION=t10 chk PASS "ordinary pyproject additions are not suppressions"

setup_repo; ins_toml 'select = ["B", "S"]' 'line-length = 100'
SESSION=t11 chk PASS "non-ignore key in the ruff section"

echo "== Signal A: pip-audit --ignore-vuln =="
setup_repo; printf 'audit:\n\t.venv/bin/pip-audit --strict --ignore-vuln GHSA-aaaa-bbbb-cccc\n' >"$tmp/repo/Makefile"
SESSION=v1 chk BLOCK "--ignore-vuln in the Makefile" "Makefile:2"

setup_repo; printf 'audit:\n\t# No fixed release yet, exposure needs a local attacker, #44\n\t.venv/bin/pip-audit --strict --ignore-vuln GHSA-aaaa-bbbb-cccc\n' >"$tmp/repo/Makefile"
SESSION=v2 chk PASS "--ignore-vuln with reference + reason above"

setup_repo; mkdir -p "$tmp/repo/.github/workflows"; printf 'jobs:\n  audit:\n    steps:\n      - run: pip-audit --ignore-vuln PYSEC-2024-1\n' >"$tmp/repo/.github/workflows/ci.yml"
SESSION=v3 chk BLOCK "--ignore-vuln in a new workflow"

echo "== Signal B: baseline =="
setup_repo; printf 'src/whitemarket/a.py:4: error: x\n' >"$tmp/repo/mypy-baseline.txt"
SESSION=b1 chk BLOCK "new analyser baseline file" "mypy-baseline.txt (+1, new file)"

setup_repo; printf 'a\nb\n' >"$tmp/repo/mypy-baseline.txt"; git -C "$tmp/repo" add -A >/dev/null; git -C "$tmp/repo" commit -qm b >/dev/null
printf 'a\n' >"$tmp/repo/mypy-baseline.txt"
SESSION=b2 chk PASS "baseline lines only removed"

echo "== Repository without commits =="
rm -rf "$tmp/repo"; mkdir -p "$tmp/repo/src/whitemarket"; git -C "$tmp/repo" init -q
printf 'x = f()  # type: ignore\n' >"$tmp/repo/src/whitemarket/a.py"
git -C "$tmp/repo" add -A >/dev/null
SESSION=e1 chk BLOCK "staged file before the first commit is scanned"

echo "== Gates =="
setup_repo; ins 'x = f()  # type: ignore'
out1="$(run g1 false)"; out2="$(run g1 false)"
if [ -n "$out1" ] && [ -z "$out2" ]; then echo "  ok    PASS  same set in the same session does not block twice"
else echo "  FAIL  session marker does not work"; fail=$((fail+1)); fi

ins 'y = g()  # noqa'
out3="$(run g1 false)"
if [ -n "$out3" ]; then echo "  ok    BLOCK a new suppression in the same session blocks again"
else echo "  FAIL  a new suppression slipped through on the old marker"; fail=$((fail+1)); fi

if [ -f "$tmp/repo/var/claude/suppress-check-done" ] && grep -qx '\*' "$tmp/repo/var/claude/.gitignore" 2>/dev/null; then
  echo "  ok    STATE marker in var/claude/ with a self-ignoring .gitignore"
else echo "  FAIL  marker not in var/claude/ or .gitignore missing"; fail=$((fail+1)); fi

out4="$(run g2 true)"
if [ -z "$out4" ]; then echo "  ok    PASS  stop_hook_active=true does not block"
else echo "  FAIL  stop_hook_active is ignored"; fail=$((fail+1)); fi

out5="$(printf '{"session_id":"g3","stop_hook_active":false}' | CLAUDE_PROJECT_DIR="$tmp/nonexistent" bash "$HOOK" 2>/dev/null)"
if [ -z "$out5" ]; then echo "  ok    PASS  outside a git repository exits quietly"
else echo "  FAIL  fired outside a repository"; fail=$((fail+1)); fi

echo "== Mutations: the cases above must turn red on a broken hook =="
MUT="$tmp/mutant.sh"
mut_chk() { # $1=want(BLOCK|PASS) $2=label $3=sed expression
  sed "$3" "$HOOK" >"$MUT"
  if cmp -s "$HOOK" "$MUT"; then printf '  FAIL  mutation did not apply: %s\n' "$2"; fail=$((fail+1)); return; fi
  local got=PASS
  [ -n "$(printf '{"session_id":"m%s","stop_hook_active":false}' "$RANDOM" \
    | CLAUDE_PROJECT_DIR="$tmp/repo" bash "$MUT" 2>/dev/null)" ] && got=BLOCK
  if [ "$got" = "$1" ]; then printf '  ok    %-5s %s\n' "$got" "$2"
  else printf '  FAIL  want=%-5s got=%-5s %s\n' "$1" "$got" "$2"; fail=$((fail+1)); fi
}

setup_repo; ins 'x = f()  # type: ignore[attr-defined]'
mut_chk PASS "without type: ignore in the list detection disappears" 's/^SUPPRESS=.#\[ \\t\]\*(type:\[ \\t\]\*ignore|/SUPPRESS='"'"'#[ \\t]*(/'

setup_repo; ins 'x = f()  # type: ignore  # stub lacks the attribute, #12'
mut_chk PASS "without the code requirement a bare type: ignore passes" 's/if (!code_ok(cur)) return 0/if (0) return 0/'

setup_repo; ins '# Generated union lacks a discriminator, see #12' 'x = f()  # type: ignore[index]'
mut_chk BLOCK "ignoring the previous line makes a reason above useless" 's/if (is_comment(prev)) words += reason_words(prev)/words += 0/; s/if (cur !~ tk \&\& prev !~ tk) return 0/if (cur !~ tk) return 0/'

setup_repo; ins 'x = f()  # type: ignore[attr-defined]  #12'
mut_chk PASS "without the reason requirement a bare #issue passes" 's/return words >= 2/return 1/'

setup_repo; ins_toml '"tests/**" = ["S101"]' '"src/whitemarket/live/**" = ["S110"]'
mut_chk PASS "pyproject.toml outside the scan is not caught" 's/^PYPROJECT=pyproject.toml/PYPROJECT=none.toml/'

setup_repo; printf 'audit:\n\tpip-audit --ignore-vuln GHSA-aaaa-bbbb-cccc\n' >"$tmp/repo/Makefile"
mut_chk PASS "Makefile outside the scan is not caught" 's/^VULN_PATHS=(Makefile /VULN_PATHS=(none.mk /'

setup_repo; printf 'x\n' >"$tmp/repo/mypy-baseline.txt"
mut_chk PASS "baseline outside the list is not caught" 's/^BASELINES=(mypy-baseline.txt /BASELINES=(none.txt /'

echo
[ "$fail" -eq 0 ] && { echo "RESULT: all cases passed"; exit 0; }
echo "RESULT: failed cases: $fail"; exit 1
