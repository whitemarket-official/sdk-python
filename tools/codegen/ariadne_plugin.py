"""ariadne-codegen plugin of the WhiteMarket SDK generated layer (ariadne-codegen 0.19.0, ADR 0001).

Runs inside the isolated codegen venv (`make install-codegen`); it is not part of the package.
Hooks used (docs/04-plugins/03-hooks.md at tag 0.19.0) and why:

- get_file_comment: the DO NOT EDIT header of every generated file.
- generate_enum / generate_enums_module: enums extend the runtime `UnknownTolerantEnum` (rule 5).
- generate_result_field: `float` -> `Decimal` (rule 3), credential-named string fields -> `Secret`
  (SDK_SPEC 8).
- generate_result_types_module / generate_fragments_module: interface and union selections decode
  by `__typename` with an unknown fallback (rule 5), plus the imports of the above.
- generate_input_field / generate_input_class / generate_inputs_module: `float` -> `Decimal`,
  explicit aliases -> `serialization_alias`, deprecated fields get `Field(deprecated=...)`,
  `FileUpload` fields are dropped (PHP DEVIATIONS 1.1).
- generate_client_method / generate_client_module: `operation_type` is passed to `execute`,
  `**kwargs` is gone, `execute` takes `document=`, answers are decoded through `self._decode`
  (a DecodeError without response data).
- copy_code: `base_model.py` takes UNSET from the runtime and hides inputs in validation errors.

The ariadne AST shapes this reads (forward references as `Name('"Cls"')`, `Literal` members
likewise) are not a stable API: the version is pinned and `make codegen-check` guards every bump.
"""

import ast
import re
from typing import Any

from ariadne_codegen.plugins.base import Plugin
from graphql import (
    ExecutableDefinitionNode,
    FieldNode,
    FragmentDefinitionNode,
    GraphQLEnumType,
    GraphQLInputField,
    GraphQLInputObjectType,
    GraphQLInterfaceType,
    GraphQLScalarType,
    GraphQLUnionType,
    OperationDefinitionNode,
    get_named_type,
)

RUNTIME = "whitemarket._runtime"
# SDK_SPEC 8: a string field whose name holds one of these, in any case, decodes into Secret.
CREDENTIAL = re.compile(
    r"token|secret|passw|authori[sz]ation|cookie|api_key|api-key|apikey|jwt|credential|proxy",
    re.IGNORECASE,
)
# `proxy` is no SDK_SPEC 8 marker, but a proxy URL may hold `user:pass@` (profile_steam_proxy_get).
# Input objects whose generic `value` field holds a credential (a proxy URL, a Steam API key): the
# field is kept out of `repr`, so a logged model never shows it. The name gives no hint: a list.
SECRET_INPUT_FIELDS = {"ProxyInput": "value", "SteamApiKeyInput": "value"}
EXCLUDED_INPUT_SCALARS = frozenset({"FileUpload"})
UNKNOWN_TAG = "__unknown__"
HEADER = (
    "# DO NOT EDIT. Generated by ariadne-codegen with tools/codegen/ariadne_plugin.py\n"
    "# from schema/partner.graphql and graphql/{operations,fragments}. Run `make codegen`."
)
UNSET_BLOCK = re.compile(
    r"class UnsetType:\n    def __bool__\(self\) -> bool:\n        return False\n\n\n"
    r"UNSET = UnsetType\(\)\n"
)
UNSET_IMPORT = (
    f"from {RUNTIME}.unset import UNSET, UnsetType\n\n"
    '__all__ = ["UNSET", "BaseModel", "UnsetType"]\n'
)


# --------------------------------------------------------------------------- AST helpers
def _rename(node: ast.AST, old: str, new: str) -> None:
    for sub in ast.walk(node):
        if isinstance(sub, ast.Name) and sub.id == old:
            sub.id = new


def _name(identifier: str) -> ast.Name:
    return ast.Name(id=identifier)


def _call(func: str, *args: ast.expr, **keywords: ast.expr) -> ast.Call:
    return ast.Call(
        func=_name(func),
        args=list(args),
        keywords=[ast.keyword(arg=k, value=v) for k, v in keywords.items()],
    )


def _subscript(base: str, *items: ast.expr) -> ast.Subscript:
    return ast.Subscript(value=_name(base), slice=ast.Tuple(elts=list(items)))


def _import(module: str, *names: str) -> ast.ImportFrom:
    return ast.ImportFrom(module=module, names=[ast.alias(name=n) for n in names], level=0)


def _add_imports(module: ast.Module, imports: list[ast.ImportFrom]) -> None:
    position = 0
    for index, stmt in enumerate(module.body):
        if isinstance(stmt, ast.Import | ast.ImportFrom):
            position = index + 1
    module.body[position:position] = imports


def _uses(module: ast.Module, name: str) -> bool:
    return any(isinstance(n, ast.Name) and n.id == name for n in ast.walk(module))


def _imports_name(module: ast.Module, from_module: str, name: str) -> bool:
    return any(
        isinstance(stmt, ast.ImportFrom)
        and stmt.module == from_module
        and any(a.name == name for a in stmt.names)
        for stmt in module.body
    )


def _literal_values(annotation: ast.expr) -> list[str] | None:
    """The members of a `Literal[...]` annotation (ariadne emits Constant or Name('"X"'))."""
    if not (
        isinstance(annotation, ast.Subscript)
        and isinstance(annotation.value, ast.Name)
        and annotation.value.id == "Literal"
    ):
        return None
    elements = (
        annotation.slice.elts if isinstance(annotation.slice, ast.Tuple) else [annotation.slice]
    )
    values: list[str] = []
    for element in elements:
        if isinstance(element, ast.Constant) and isinstance(element.value, str):
            values.append(element.value)
        elif isinstance(element, ast.Name):
            values.append(element.id.strip('"'))
    return values


def _typename_stmt(class_def: ast.ClassDef) -> ast.AnnAssign | None:
    for stmt in class_def.body:
        if (
            isinstance(stmt, ast.AnnAssign)
            and isinstance(stmt.target, ast.Name)
            and stmt.target.id == "typename__"
        ):
            return stmt
    return None


def _is_discriminator_field(node: ast.expr) -> bool:
    return (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id == "Field"
        and any(k.arg == "discriminator" for k in node.keywords)
    )


def _ref_name(node: ast.expr) -> str:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.Name):
        return node.id.strip('"')  # ariadne emits forward references as Name('"Cls"')
    raise ValueError(f"unexpected union member {ast.dump(node)}")


def _tagged(member: ast.expr, tag: str) -> ast.Subscript:
    return _subscript("Annotated", member, _call("Tag", ast.Constant(tag)))


def _fallback_class(name: str) -> ast.ClassDef:
    field = ast.AnnAssign(
        target=_name("typename__"),
        annotation=_name("str"),
        value=_call("Field", alias=ast.Constant("__typename")),
        simple=1,
    )
    doc = ast.Expr(
        value=ast.Constant("A type the schema snapshot does not know; only __typename is decoded.")
    )
    return ast.ClassDef(
        name=name,
        bases=[_name("BaseModel")],
        keywords=[],
        body=[doc, field],
        decorator_list=[],
        type_params=[],
    )


def _common_prefix(names: list[str]) -> str:
    prefix = names[0]
    for name in names[1:]:
        while not name.startswith(prefix):
            prefix = prefix[:-1]
    return prefix


# --------------------------------------------------------------------------- the plugin
class WhiteMarketPlugin(Plugin):
    def __init__(self, schema: Any, config_dict: dict[str, Any]) -> None:
        super().__init__(schema, config_dict)
        self._dropped_inputs: set[int] = set()
        self._abstract = {
            name
            for name, type_ in schema.type_map.items()
            if isinstance(type_, GraphQLInterfaceType | GraphQLUnionType)
        }

    # ------------------------------------------------------------------ header
    def get_file_comment(self, comment: str, code: str, source: str | None = None) -> str:
        return HEADER

    # ------------------------------------------------------------------ enums
    def generate_enum(self, class_def: ast.ClassDef, enum_type: GraphQLEnumType) -> ast.ClassDef:
        class_def.bases = [_name("UnknownTolerantEnum")]
        return class_def

    def generate_enums_module(self, module: ast.Module) -> ast.Module:
        module.body = [
            s for s in module.body if not (isinstance(s, ast.ImportFrom) and s.module == "enum")
        ]
        _add_imports(module, [_import(f"{RUNTIME}.enums", "UnknownTolerantEnum")])
        return module

    # ------------------------------------------------------------------ results
    def generate_result_field(
        self,
        field_implementation: ast.AnnAssign,
        operation_definition: ExecutableDefinitionNode,
        field: FieldNode,
    ) -> ast.AnnAssign:
        _rename(field_implementation.annotation, "float", "Decimal")
        if CREDENTIAL.search(field.name.value):
            _rename(field_implementation.annotation, "str", "Secret")
        return field_implementation

    def generate_result_types_module(
        self, module: ast.Module, operation_definition: ExecutableDefinitionNode
    ) -> ast.Module:
        return self._finish_result_module(module)

    def generate_fragments_module(
        self, module: ast.Module, fragments_definitions: dict[str, FragmentDefinitionNode]
    ) -> ast.Module:
        return self._finish_result_module(module)

    def _finish_result_module(self, module: ast.Module) -> ast.Module:
        classes = {s.name: s for s in module.body if isinstance(s, ast.ClassDef)}
        literals = self._widen_abstract_typenames(classes)
        _hoist_field_discriminators(module)
        used_typename, extra = self._rewrite_unions(module, classes, literals)
        if extra:
            first = next(i for i, st in enumerate(module.body) if isinstance(st, ast.ClassDef))
            module.body[first:first] = extra
        _fix_result_imports(module, used_typename=used_typename)
        return module

    def _widen_abstract_typenames(self, classes: dict[str, ast.ClassDef]) -> dict[str, list[str]]:
        """A `__typename` Literal naming an abstract type becomes `str`: any server type decodes.

        That is the fallback member of a union and a `__typename id` selection at the depth limit.
        Returns the Literal values of every class before the change.
        """
        literals: dict[str, list[str]] = {}
        for name, class_def in classes.items():
            stmt = _typename_stmt(class_def)
            values = _literal_values(stmt.annotation) if stmt else None
            if stmt is None or values is None:
                continue
            literals[name] = values
            if any(v in self._abstract for v in values):
                stmt.annotation = _name("str")
        return literals

    def _rewrite_unions(
        self,
        module: ast.Module,
        classes: dict[str, ast.ClassDef],
        literals: dict[str, list[str]],
    ) -> tuple[bool, list[ast.ClassDef]]:
        """Turn each `Annotated[Union[...], Field(discriminator=...)]` into a tagged union with a
        callable discriminator that routes unknown `__typename` values to a fallback member."""
        used = False
        extra: list[ast.ClassDef] = []
        for node in list(ast.walk(module)):
            if not (
                isinstance(node, ast.Subscript)
                and isinstance(node.value, ast.Name)
                and node.value.id == "Annotated"
                and isinstance(node.slice, ast.Tuple)
                and _is_discriminator_field(node.slice.elts[-1])
            ):
                continue
            union = node.slice.elts[0]
            if not (isinstance(union, ast.Subscript) and isinstance(union.slice, ast.Tuple)):
                raise ValueError(f"unexpected discriminated type {ast.dump(union)}")
            known = self._tag_members(union.slice, classes, literals, extra)
            node.slice.elts[-1] = _call("typename_discriminator", *[ast.Constant(k) for k in known])
            used = True
        return used, extra

    def _tag_members(
        self,
        union_args: ast.Tuple,
        classes: dict[str, ast.ClassDef],
        literals: dict[str, list[str]],
        extra: list[ast.ClassDef],
    ) -> list[str]:
        """Tag every member of one union in place; returns the known `__typename` values."""
        known: list[str] = []
        fallback: str | None = None
        tagged: list[ast.expr] = []
        for member in union_args.elts:
            ref = _ref_name(member)
            values = literals.get(ref)
            if values is None:
                raise ValueError(f"union member {ref} has no __typename Literal")
            if any(v in self._abstract for v in values):
                if fallback is not None:
                    raise ValueError(f"two fallback members in union: {fallback}, {ref}")
                fallback = ref
                tagged.append(_tagged(member, UNKNOWN_TAG))
            else:
                (tag,) = values
                known.append(tag)
                tagged.append(_tagged(member, tag))
        if fallback is None:
            # Every possible type is selected (MarketProductUnion): add a fallback model.
            names = [_ref_name(m) for m in union_args.elts]
            fallback = f"{_common_prefix(names)}UnknownTypename"
            if fallback not in classes:
                classes[fallback] = _fallback_class(fallback)
                extra.append(classes[fallback])
            tagged.append(_tagged(ast.Constant(fallback), UNKNOWN_TAG))
        union_args.elts = tagged
        return known

    # ------------------------------------------------------------------ inputs
    def generate_input_field(
        self, field_implementation: ast.AnnAssign, input_field: GraphQLInputField, field_name: str
    ) -> ast.AnnAssign:
        _rename(field_implementation.annotation, "float", "Decimal")
        named = get_named_type(input_field.type)
        if isinstance(named, GraphQLScalarType) and named.name in EXCLUDED_INPUT_SCALARS:
            self._dropped_inputs.add(id(field_implementation))
        value = field_implementation.value
        if isinstance(value, ast.Call):
            for keyword in value.keywords:
                # `from` / `type` keep an explicit alias; as `alias` it would become the __init__
                # parameter name for type checkers (dataclass_transform), and `from` is a keyword.
                if keyword.arg == "alias":
                    keyword.arg = "serialization_alias"
        if input_field.deprecation_reason:
            _mark_deprecated(field_implementation, input_field.deprecation_reason)
        return field_implementation

    def generate_input_class(
        self, class_def: ast.ClassDef, input_type: GraphQLInputObjectType
    ) -> ast.ClassDef:
        body: list[ast.stmt] = []
        skip_doc = False
        for stmt in class_def.body:
            if skip_doc and isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant):
                skip_doc = False
                continue  # the dropped field's description
            skip_doc = False
            if id(stmt) in self._dropped_inputs:
                skip_doc = True
                continue
            body.append(stmt)
        class_def.body = body
        secret_field = SECRET_INPUT_FIELDS.get(input_type.name)
        for stmt in class_def.body:
            if (
                secret_field is not None
                and isinstance(stmt, ast.AnnAssign)
                and isinstance(stmt.target, ast.Name)
                and stmt.target.id == secret_field
            ):
                _add_field_keyword(stmt, "repr", ast.Constant(False))
        return class_def

    def generate_inputs_module(self, module: ast.Module) -> ast.Module:
        if _uses(module, "Decimal"):
            _add_imports(module, [_import("decimal", "Decimal")])
        return module

    # ------------------------------------------------------------------ client
    def generate_client_method(
        self,
        method_def: ast.FunctionDef | ast.AsyncFunctionDef,
        operation_definition: OperationDefinitionNode,
    ) -> ast.FunctionDef | ast.AsyncFunctionDef:
        method_def.args.kwarg = None
        operation_type = operation_definition.operation.value  # "query" | "mutation"
        for node in ast.walk(method_def):
            if not isinstance(node, ast.Call):
                continue
            if isinstance(node.func, ast.Attribute) and node.func.attr == "execute":
                _rewrite_execute_call(node, operation_type)
            elif isinstance(node.func, ast.Attribute) and node.func.attr == "model_validate":
                _rewrite_model_validate(node)
        return method_def

    def generate_client_module(self, module: ast.Module) -> ast.Module:
        # Any is no longer used once **kwargs is gone, unless an argument is typed Any.
        if not _uses(module, "Any"):
            for stmt in module.body:
                if isinstance(stmt, ast.ImportFrom) and stmt.module == "typing":
                    stmt.names = [a for a in stmt.names if a.name != "Any"]
        return module

    # ------------------------------------------------------------------ copied files
    def copy_code(self, copied_code: str) -> str:
        if "class BaseModel(PydanticBaseModel)" not in copied_code:
            return copied_code
        rewritten, count = UNSET_BLOCK.subn(
            UNSET_IMPORT,
            copied_code,
        )
        # A changed ariadne template must fail the run, not silently emit the stock file.
        if count != 1 or "protected_namespaces=()," not in rewritten:
            raise RuntimeError("ariadne base_model.py template changed: update copy_code")
        return rewritten.replace(
            "protected_namespaces=(),",
            "protected_namespaces=(),\n        hide_input_in_errors=True,",
        )


# --------------------------------------------------------------------------- hook helpers
def _hoist_field_discriminators(module: ast.Module) -> None:
    """Move a discriminator from a field default into an `Annotated[...]`.

    Non-null union fields carry it as `= Field(alias=..., discriminator=...)`; the union pass
    wants one shape.
    """
    for node in ast.walk(module):
        if (
            isinstance(node, ast.AnnAssign)
            and isinstance(node.value, ast.Call)
            and _is_discriminator_field(node.value)
        ):
            node.value.keywords = [k for k in node.value.keywords if k.arg != "discriminator"]
            node.annotation = _subscript(
                "Annotated",
                node.annotation,
                _call("Field", discriminator=ast.Constant("typename__")),
            )


def _fix_result_imports(module: ast.Module, *, used_typename: bool) -> None:
    imports: list[ast.ImportFrom] = []
    if _uses(module, "Decimal"):
        imports.append(_import("decimal", "Decimal"))
    if used_typename:
        imports.append(_import("pydantic", "Tag"))
        if not _imports_name(module, "typing", "Annotated"):
            imports.append(_import("typing", "Annotated"))
        imports.append(_import(f"{RUNTIME}.typename", "typename_discriminator"))
    if _uses(module, "Secret"):
        imports.append(_import(f"{RUNTIME}.secret", "Secret"))
    if not any(
        isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id == "Field"
        for n in ast.walk(module)
    ):
        module.body = [
            s
            for s in module.body
            if not (
                isinstance(s, ast.ImportFrom)
                and s.module == "pydantic"
                and [a.name for a in s.names] == ["Field"]
            )
        ]
    _add_imports(module, imports)


def _mark_deprecated(field_implementation: ast.AnnAssign, reason: str) -> None:
    _add_field_keyword(field_implementation, "deprecated", ast.Constant(reason))


def _add_field_keyword(field_implementation: ast.AnnAssign, name: str, argument: ast.expr) -> None:
    """`x: T` or `x: T = d` becomes `x: T = Field(default=d, <name>=<argument>)`; an existing
    `Field(...)` gets the keyword."""
    value = field_implementation.value
    marker = ast.keyword(arg=name, value=argument)
    if (
        isinstance(value, ast.Call)
        and isinstance(value.func, ast.Name)
        and value.func.id == "Field"
    ):
        value.keywords.append(marker)
        return
    keywords = [marker] if value is None else [ast.keyword(arg="default", value=value), marker]
    field_implementation.value = ast.Call(func=_name("Field"), args=[], keywords=keywords)


def _rewrite_execute_call(node: ast.Call, operation_type: str) -> None:
    keywords = [k for k in node.keywords if k.arg is not None]  # drop **kwargs
    for keyword in keywords:
        if keyword.arg == "query":
            keyword.arg = "document"
    keywords.append(ast.keyword(arg="operation_type", value=ast.Constant(operation_type)))
    node.keywords = keywords


def _rewrite_model_validate(node: ast.Call) -> None:
    """`Model.model_validate(data)` -> `self._decode(Model, data)`."""
    if not isinstance(node.func, ast.Attribute):
        raise TypeError("model_validate call without an attribute access")
    model = node.func.value
    node.func = ast.Attribute(value=_name("self"), attr="_decode", ctx=ast.Load())
    node.args = [model, *node.args]
