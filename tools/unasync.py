"""Derive the sync code from the async code by deterministic token rewriting (as httpcore does).

Usage (from the repository root; `make codegen` runs it, do not call it by hand):

    python tools/unasync.py [--check] --tree SRC DST     # every *.py of a tree, stale files removed
    python tools/unasync.py [--check] --file SRC DST     # one file

The rules are the explicit table `RULES` below, applied in order to every NAME token, plus the
keywords `async` and `await`, which are deleted (comments and prose are not touched; a string that
is only a name or type expression is renamed too).
Afterwards the result is scanned for tokens that must not survive in sync code (`async`, `await`,
`asyncio`, `Async...`): such a token means the async source used something the table does not
know, and the run fails instead of emitting broken code. Async source gets its primitives from
`whitemarket/_concurrency.py` (hand-written
pairs `AsyncLock`/`Lock`, `async_sleep`/`sleep`), never from `asyncio` directly.

`--check` writes nothing and exits 1 when a destination differs from the rewrite of its source (the
Makefile formats `_sync` with ruff afterwards, so `make codegen-check` is the full check).
"""

import argparse
import io
import re
import sys
import tokenize
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
HEADER = "# DO NOT EDIT: generated by tools/unasync.py from {source}\n"
GENERATED_MARK = "# DO NOT EDIT"


@dataclass(frozen=True)
class Rule:
    name: str
    pattern: re.Pattern[str]
    replacement: str


def _rule(name: str, pattern: str, replacement: str) -> Rule:
    return Rule(name, re.compile(pattern), replacement)


# Applied to every NAME token (never to comments or prose in strings), in order. The keywords
# `async` and `await` have no rule: `_KEYWORDS` below deletes the token and the blank after it.
RULES: tuple[Rule, ...] = (
    _rule("__aenter__", r"\A__aenter__\Z", "__enter__"),
    _rule("__aexit__", r"\A__aexit__\Z", "__exit__"),
    _rule("__aiter__", r"\A__aiter__\Z", "__iter__"),
    _rule("__anext__", r"\A__anext__\Z", "__next__"),
    _rule("StopAsyncIteration", r"\AStopAsyncIteration\Z", "StopIteration"),
    _rule("asynccontextmanager", r"\Aasynccontextmanager\Z", "contextmanager"),
    _rule("aclose", r"\Aaclose\Z", "close"),
    _rule("aread", r"\Aaread\Z", "read"),
    _rule("aiter_x", r"\Aaiter_(?=bytes\Z|text\Z|lines\Z|raw\Z)", "iter_"),
    _rule("anext", r"\Aanext\Z", "next"),
    _rule("aiter", r"\Aaiter\Z", "iter"),
    # AsyncX -> X and _AsyncX -> _X: AsyncGraphQLBase, httpx.AsyncClient, AsyncLock, ...
    _rule("AsyncX", r"\A(_?)Async(?=[A-Z])", r"\1"),
    # async_x -> x and _async_x -> _x: async_sleep, and the module name async_base_client.
    _rule("async_x", r"\A(_?)async_(?=\w)", r"\1"),
    # Imports and paths: whitemarket._async.x -> whitemarket._sync.x
    _rule("_async", r"\A_async\Z", "_sync"),
)

_KEYWORDS = frozenset({"async", "await"})
_FORBIDDEN_NAMES = frozenset(
    {"async", "await", "asyncio", "asynccontextmanager", "aclose", "aread", "anext", "aiter"}
)
_FORBIDDEN_NAME = re.compile(
    r"^(_?Async[A-Z]|_?async_|aiter_|_async$|StopAsyncIteration$|__a(enter|exit|iter|next)__$)"
)
# A string that is only a name or a type expression (`__all__` entries, forward references)
# follows the names; prose and anything else is left alone.
_NAME_STRING = re.compile(r"""(["'])([A-Za-z_][\w.]*(?:\[[\w.,\[\] |]*\])?)\1""")
_IDENTIFIER = re.compile(r"\w+")


class UnasyncError(Exception):
    """The source holds something the rule table cannot turn into sync code."""


def _rename(name: str) -> str:
    """The sync spelling of one identifier (keywords are not handled here)."""
    for rule in RULES:
        name = rule.pattern.sub(rule.replacement, name)
    return name


def _name_edit(
    token: tokenize.TokenInfo, previous: list[tokenize.TokenInfo], text: str, begin: int, end: int
) -> tuple[int, int, str] | None:
    if token.string in _KEYWORDS:
        while end < len(text) and text[end] in " \t":
            end += 1
        return (begin, end, "")
    if token.string == "client" and [t.string for t in previous[-2:]] == ["_generated", "."]:
        return (begin, end, "sync_client")
    renamed = _rename(token.string)
    return (begin, end, renamed) if renamed != token.string else None


def _string_edit(token: tokenize.TokenInfo, begin: int, end: int) -> tuple[int, int, str] | None:
    match = _NAME_STRING.fullmatch(token.string)
    if match is None:
        return None
    body = _IDENTIFIER.sub(lambda m: _rename(m.group(0)), match.group(2))
    if body == match.group(2):
        return None
    return (begin, end, f"{match.group(1)}{body}{match.group(1)}")


def rewrite(text: str) -> str:
    """Rewrite NAME tokens by the rule table; comments and prose stay as they are.

    The module path `_generated.client` becomes `_generated.sync_client` (the sync generated
    client lives in its own module).
    """
    starts = [0]
    for line in io.StringIO(text).readlines():
        starts.append(starts[-1] + len(line))
    edits: list[tuple[int, int, str]] = []
    previous: list[tokenize.TokenInfo] = []
    for token in tokenize.generate_tokens(io.StringIO(text).readline):
        begin = starts[token.start[0] - 1] + token.start[1]
        end = starts[token.end[0] - 1] + token.end[1]
        edit = None
        if token.type == tokenize.NAME:
            edit = _name_edit(token, previous, text, begin, end)
        elif token.type == tokenize.STRING:
            edit = _string_edit(token, begin, end)
        if edit is not None:
            edits.append(edit)
        if token.type not in (tokenize.NL, tokenize.COMMENT):
            previous.append(token)
            del previous[:-2]
    for begin, end, replacement in reversed(edits):
        text = text[:begin] + replacement + text[end:]
    return text


def leftovers(code: str) -> list[str]:
    """Names in the rewritten code (strings and comments excluded) that sync code must not hold."""
    found: list[str] = []
    for token in tokenize.generate_tokens(io.StringIO(code).readline):
        if token.type != tokenize.NAME:
            continue
        if token.string in _FORBIDDEN_NAMES or _FORBIDDEN_NAME.match(token.string):
            found.append(f"{token.string} (line {token.start[0]})")
    return found


def convert(text: str, source_label: str) -> str:
    """Rewrite one source file; add the DO NOT EDIT header unless the source has one already."""
    result = rewrite(text)
    left = leftovers(result)
    if left:
        raise UnasyncError(f"{source_label}: no rule for {', '.join(left)}")
    if result.startswith(GENERATED_MARK) or not result:
        return result
    return HEADER.format(source=source_label) + result


def _label(path: Path) -> str:
    resolved = path.resolve()
    try:
        return resolved.relative_to(REPO).as_posix()
    except ValueError:
        return resolved.as_posix()


def _plan_tree(src: Path, dst: Path) -> dict[Path, str]:
    return {
        dst / source.relative_to(src): convert(source.read_text(encoding="utf-8"), _label(source))
        for source in sorted(src.rglob("*.py"))
        if "__pycache__" not in source.parts
    }


def _stale(dst: Path, planned: dict[Path, str]) -> list[Path]:
    if not dst.is_dir():
        return []
    return [
        p for p in sorted(dst.rglob("*.py")) if "__pycache__" not in p.parts and p not in planned
    ]


def run(
    files: list[tuple[Path, Path]], trees: list[tuple[Path, Path]], *, check: bool
) -> list[str]:
    """Write the sync files, or with `check` only compare them; returns the problems found."""
    planned: dict[Path, str] = {}
    stale: list[Path] = []
    for src, dst in trees:
        tree_plan = _plan_tree(src, dst)
        planned.update(tree_plan)
        stale.extend(_stale(dst, tree_plan))
    for src, dst in files:
        planned[dst] = convert(src.read_text(encoding="utf-8"), _label(src))
    problems: list[str] = []
    for path, text in planned.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            problems.append(f"{'missing' if current is None else 'differs'}: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    for path in stale:
        if check:
            problems.append(f"stale: {path}")
        else:
            path.unlink()
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument(
        "--check", action="store_true", help="write nothing, exit 1 on any difference"
    )
    parser.add_argument("--file", nargs=2, action="append", default=[], metavar=("SRC", "DST"))
    parser.add_argument("--tree", nargs=2, action="append", default=[], metavar=("SRC", "DST"))
    args = parser.parse_args(argv)
    files = [(Path(s), Path(d)) for s, d in args.file]
    trees = [(Path(s), Path(d)) for s, d in args.tree]
    try:
        problems = run(files, trees, check=args.check)
    except UnasyncError as error:
        sys.stderr.write(f"unasync: {error}\n")
        return 2
    for problem in problems:
        sys.stderr.write(f"unasync: {problem}\n")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
